"""t21_tuning_table.py -- the tuning section's table, from tuned.csv and flagship.csv.

Two things belong in that section and they answer different questions.

  tuned.csv     every arm searched at the same budget on the same temporal inner
                split. Answers: does the lead survive when the competitors are
                tuned as hard as the method?
  flagship.csv  Dynamic ET searched over Step 1 itself -- which coordinates the
                surface is written in, the scale of the target, the weighting of
                the window. Answers: what does the method reach when the part
                that belongs to it is searched?
"""
import sys, warnings
from pathlib import Path
warnings.filterwarnings('ignore')
import numpy as np, pandas as pd
from scipy.stats import wilcoxon

HERE = Path(__file__).resolve().parents[1]
PAPER = Path(os.environ.get('DYNET_FIGDIR', 'figures/out'))
OURS = 'Dynamic ET (tuned)'
# the code names the coordinate sets by appended terms; the paper by total width
SETNAME = {'ship8': r'\texttt{clean15}', 'surface12': r'\texttt{surface19}',
           'surface16': r'\texttt{surface23}'}


def paired(t, a, b, col='r2'):
    x = t[t.model == a].set_index('fold')[col]
    y = t[t.model == b].set_index('fold')[col]
    j = x.index.intersection(y.index)
    d = (x[j] - y[j]).dropna()
    if len(d) < 3 or (d == 0).all():
        return np.nan, 0, len(d), np.nan
    return d.mean(), int((d > 0).sum()), len(d), wilcoxon(d, alternative='greater').pvalue


def tuned_table():
    t = pd.read_csv(HERE / 'results' / 'tuned.csv')
    full = t.groupby('model').fold.nunique().max()
    t = t[t.model.isin(t.groupby('model').fold.nunique().pipe(lambda s: s[s == full]).index)]
    g = (t.groupby('model')[['r2', 'mae', 'search_s', 'fit_s', 'pred_s']].mean()
          .sort_values('r2', ascending=False))
    lines = [r'% generated by TKDE2026/code/t21_tuning_table.py',
             r'\begin{table*}[t]', r'\centering',
             r'\caption{Every arm searched at the same budget --- forty',
             r'configurations drawn from its own grid, scored on a temporal inner',
             r'split of the training window, the test quarter never read. Search',
             r'and fit seconds are reported separately so the price of tuning is',
             r'visible. $\Delta R^{2}$ and $p$ are against tuned Dynamic ET over',
             f'the {full} folds, one-sided Wilcoxon signed-rank.'.replace('_', r'\_'),
             r'}', r'\label{tab:tuned}', r'\small',
             r'\begin{tabular}{lrrrrr}', r'\toprule',
             r'arm & $R^{2}$ & MAE & search (s) & fit (s) & $\Delta R^{2}$ ($p$) \\',
             r'\midrule']
    for m, r in g.iterrows():
        if m == OURS:
            nm = r'\textbf{Dynamic ET (tuned, ours)}'
            cells = (f'\\textbf{{{r.r2:.4f}}}', f'\\textbf{{{r.mae:.4f}}}',
                     f'{r.search_s:.0f}', f'\\textbf{{{r.fit_s:.1f}}}', '---')
        else:
            d, w, n, p = paired(t, OURS, m)
            ps = r'<10^{-4}' if p == p and p < 1e-4 else (f'{p:.4f}' if p == p else '---')
            nm = m.replace('_', r'\_')
            sc = '---' if r.search_s < 0.05 else f'{r.search_s:.0f}'
            cells = (f'{r.r2:.4f}', f'{r.mae:.4f}', sc, f'{r.fit_s:.1f}',
                     f'${-d:+.4f}$ (${ps}$, {w}/{n})')
        lines.append(nm + ' & ' + ' & '.join(cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table*}']
    (PAPER / 'table_tuned.tex').write_text('\n'.join(lines) + '\n')
    print(g.to_string(float_format=lambda x: f'{x:.4f}'))
    for m in g.index:
        if m == OURS: continue
        d, w, n, p = paired(t, OURS, m)
        print(f'  vs {m:<22} dR2={d:+.4f}  {w}/{n}  p={p:.4g}')
    return g, full


def flagship_table():
    f = pd.read_csv(HERE / 'results' / 'flagship.csv')
    dlt = f.r2 - f.base_r2
    p = wilcoxon(dlt, alternative='greater').pvalue if len(dlt) > 2 else np.nan
    lines = [r'% generated by TKDE2026/code/t21_tuning_table.py',
             r'\begin{table*}[t]', r'\centering',
             r'\caption{Step~1 searched on the training window. Each fold selects',
             r'a coordinate set from Table~\ref{tab:augment}, a target scale, an',
             r'exponential recency half-life over the four-quarter window, and a',
             r'leaf size, on a temporal inner split; the winner is refit on the',
             r'whole window before the test quarter is read. The first row is the',
             r'configuration specified in Section~\ref{sec:method}.}',
             r'\label{tab:flagship}', r'\small',
             r'\begin{tabular}{lrrrr}', r'\toprule',
             r'arm & $R^{2}$ & MAE & search (s) & fit (s) \\', r'\midrule',
             f'Dynamic ET, as specified & {f.base_r2.mean():.4f} & {f.base_mae.mean():.4f}'
             f' & --- & {f.base_fit_s.mean():.1f} \\\\',
             r'\textbf{Dynamic ET, Step~1 searched} & '
             f'\\textbf{{{f.r2.mean():.4f}}} & \\textbf{{{f.mae.mean():.4f}}} & '
             f'{f.search_s.mean():.0f} & {f.fit_s.mean():.1f} \\\\',
             r'\midrule',
             f'\\multicolumn{{5}}{{l}}{{$\\Delta R^{{2}} = {dlt.mean():+.4f}$, '
             f'ahead on {int((dlt>0).sum())} of {len(dlt)} folds, '
             f'Wilcoxon $p={p:.3f}$}} \\\\',
             r'\bottomrule', r'\end{tabular}', r'\end{table*}']
    (PAPER / 'table_flagship.tex').write_text('\n'.join(lines) + '\n')
    print(f'\nflagship: as specified {f.base_r2.mean():.4f} -> searched {f.r2.mean():.4f}'
          f'  ({dlt.mean():+.4f}, {int((dlt>0).sum())}/{len(dlt)}, p={p:.4g})')
    for c, lab in (('aug', 'coordinate set'), ('target', 'target scale'),
                   ('halflife', 'half-life'), ('leaf', 'leaf')):
        v = f[c].astype(str).value_counts().to_dict()
        print(f'  chosen {lab}: ' +
              ', '.join(f'{SETNAME.get(k,k)}: {n}'.replace('\\texttt','') for k, n in v.items()))
    return f


if __name__ == '__main__':
    if (HERE / 'results' / 'tuned.csv').exists():
        tuned_table()
    if (HERE / 'results' / 'flagship.csv').exists():
        flagship_table()
